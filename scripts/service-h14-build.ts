import { existsSync, mkdtempSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deriveCertifiedEngineBuild } from './certified-engine-build.ts';
import { assertServiceH14Native } from './service-h14-native-integrity.ts';
import { deriveServiceH14Build, serviceH14BuildContents } from './service-h14-integrity.ts';
import { assertServiceH14Node, SERVICE_H14_BUILD_FILE, serviceH14Directory, serviceH14Path, serviceH14Root, serviceH14Run, serviceH14Sha256 } from './service-h14-paths.ts';

/** Separate processes are intentional: authority/profile modules must not cache a
 * pre-refresh core hash while the new service identity is being derived. */
export async function refreshServiceH14Core(): Promise<void> {
  assertServiceH14Node();
  const root = serviceH14Root(), run = serviceH14Run(root);
  // This derivation validates unchanged forecast authority, provenance and WASM
  // source/byte pins before allowing the one permitted core codeHash refresh.
  const derived = await deriveCertifiedEngineBuild(pathToFileURL(`${root}/`));
  if (derived.sources.some(source => source.path.startsWith('src/serviceH14/')))
    throw new Error('service_h14_core_runtime_identity_cycle');
  const previous = readFileSync(derived.output, 'utf8');
  if (!/^\/\/ Generated by scripts\/certified-engine-build\.ts; checked before product builds\.\nexport const CERTIFIED_ENGINE_CODE_HASH = "[a-f0-9]{64}";\n$/.test(previous))
    throw new Error('service_h14_core_metadata_shape_changed');
  const contents = `// Generated by scripts/certified-engine-build.ts; checked before product builds.\nexport const CERTIFIED_ENGINE_CODE_HASH = "${derived.codeHash}";\n`;
  const attempt = mkdtempSync(resolve(run, 'core-identity.'));
  writeFileSync(resolve(attempt, 'previous-certifiedEngineBuild.ts'), previous, { flag: 'wx', mode: 0o600 });
  writeFileSync(resolve(attempt, 'derivation.json'), JSON.stringify(derived, null, 2), { flag: 'wx', mode: 0o600 });
  if (previous !== contents) {
    const temporary = resolve(attempt, 'certifiedEngineBuild.ts');
    writeFileSync(temporary, contents, { flag: 'wx', mode: 0o600 });
    renameSync(temporary, serviceH14Path(root, derived.output));
  }
  const receipt = { status: 'NONDEPLOYABLE_LOCAL_PREVIEW', changed: previous !== contents,
    previousMetadataSha256: serviceH14Sha256(previous), codeHash: derived.codeHash,
    forecastAuthorityChanged: false, oldWasmChanged: false, productionProposalChanged: false };
  writeFileSync(resolve(attempt, 'receipt.json'), JSON.stringify(receipt, null, 2), { flag: 'wx', mode: 0o600 });
  console.log(JSON.stringify({ attempt, ...receipt }));
}

export async function generateServiceH14Identity(): Promise<void> {
  assertServiceH14Node();
  const root = serviceH14Root(), run = serviceH14Run(root);
  const native = await assertServiceH14Native(root);
  const identity = await deriveServiceH14Build(root, native);
  const attempt = mkdtempSync(resolve(run, 'runtime-identity.'));
  const output = serviceH14Path(root, SERVICE_H14_BUILD_FILE);
  serviceH14Directory(root, dirname(output));
  if (existsSync(output)) writeFileSync(resolve(attempt, 'previous-build.ts'), readFileSync(output), { flag: 'wx', mode: 0o600 });
  const temporary = resolve(attempt, 'build.ts');
  writeFileSync(temporary, serviceH14BuildContents(identity), { flag: 'wx', mode: 0o600 });
  renameSync(temporary, output);
  const receipt = { status: 'NONDEPLOYABLE_SERVICE_CANDIDATE', ...identity,
    forecastAuthorityChanged: false, oldWasmChanged: false, productionProposalChanged: false,
    promotionGate: 'NOT_APPROVED', analyticsProviderGate: 'APPROVED_PRODUCER_CODE_REQUIRED' };
  writeFileSync(resolve(attempt, 'receipt.json'), JSON.stringify(receipt, null, 2), { flag: 'wx', mode: 0o600 });
  console.log(JSON.stringify({ attempt, ...receipt }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 3 || !['--core', '--identity'].includes(process.argv[2]!))
    throw new Error('Usage: node scripts/service-h14-build.ts --core|--identity (native build runs between these, in a separate process)');
  if (process.argv[2] === '--core') await refreshServiceH14Core();
  else await generateServiceH14Identity();
}
