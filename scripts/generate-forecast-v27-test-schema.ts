import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";

const root = resolve(import.meta.dirname, "..");
const db = new DatabaseSync(":memory:");
db.exec(readFileSync(resolve(root, "forecast-collector/schema.sql"), "utf8"));
for (const name of [
  "0022_forecast_runtime_versions",
  "0023_forecast_runtime_publication",
  "0024_runtime_ingestion",
  "0025_naver_page_policy",
  "0026_source_judgment_evidence",
  "0027_board11_grants",
  "0028_publication_exclusions",
  "0029_candidate_replay_cache",
  "0030_monitor_streams",
  "0031_calendar_decisions",
  "0032_grant_occurrences",
  "0033_calendar_snapshots",
  "0034_runtime_publication_v5",
]) {
  db.exec(readFileSync(resolve(root, `forecast-collector/migrations/${name}.sql`), "utf8"));
}
const schema = db
  .prepare("SELECT sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'")
  .all()
  .map((row) => `${row["sql"]};`)
  .join("\n");
const ledger = db
  .prepare("SELECT version FROM schema_migrations ORDER BY version")
  .all()
  .map((row) => `INSERT INTO schema_migrations VALUES(${row["version"]},CURRENT_TIMESTAMP);`)
  .join("\n");
const monitorSeeds = db
  .prepare("SELECT * FROM forecast_v2_monitors ORDER BY stream_id")
  .all()
  .map(
    (row) =>
      `INSERT INTO forecast_v2_monitors VALUES(${Object.values(row)
        .map((value) =>
          value === null
            ? "NULL"
            : typeof value === "number"
              ? String(value)
              : `'${String(value).replaceAll("'", "''")}'`,
        )
        .join(",")});`,
  )
  .join("\n");
writeFileSync(
  resolve(root, "forecast-collector/fixtures/schema-v27-test.sql"),
  `-- Generated by scripts/generate-forecast-v27-test-schema.ts.\n${schema}\n${ledger}\n${monitorSeeds}\nINSERT INTO forecast_v2_monitor_state(stream_id,updated_at) SELECT stream_id,CURRENT_TIMESTAMP FROM forecast_v2_monitors;\n`,
);
db.close();
