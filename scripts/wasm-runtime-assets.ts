import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CERTIFIED_WASM_HASH } from "../shared/generated/certifiedWasmBuild.ts";
import { assertCertifiedWasmBuild } from "./certified-wasm-build-inputs.ts";

const ROOT = new URL("../", import.meta.url);
const LEGACY_APPROVED_HASH = "8a910a2494e90f2ae8b7d0e9f0faab94419c76f5f93c23424d7a86efdc8c17e1";
const GENERATED = "shared/generated/wasmRuntimeAssets.ts";
export function deriveWasmRuntimeAssets(root = ROOT) {
  assertCertifiedWasmBuild(root);
  const definitions = [
    ["LEGACY", "solver_rs", LEGACY_APPROVED_HASH],
    ["CERTIFIED", "certified_solver", CERTIFIED_WASM_HASH],
  ] as const;
  return definitions.map(([role, name, expected]) => {
    const canonical = `public/${name}.wasm`;
    const bytes = readFileSync(new URL(canonical, root));
    const hash = createHash("sha256").update(bytes).digest("hex");
    if (hash !== expected) throw new Error(`wasm_canonical_pin_mismatch:${role}`);
    return { role, canonical, asset: { file: `wasm/${name}.${hash}.wasm`, sha256: hash, bytes: bytes.length } };
  });
}
function contents(definitions: ReturnType<typeof deriveWasmRuntimeAssets>) {
  return "// Generated by scripts/wasm-runtime-assets.ts from approved canonical build inputs.\n" +
    definitions.map(({ role, asset }) =>
      `export const ${role}_WASM_ASSET = ${JSON.stringify(asset, null, 2)} as const;\n`).join("");
}
export function assertWasmRuntimeAssets(root = ROOT) {
  const definitions = deriveWasmRuntimeAssets(root);
  if (readFileSync(new URL(GENERATED, root), "utf8") !== contents(definitions))
    throw new Error("wasm_runtime_asset_projection_stale");
  for (const { asset } of definitions) {
    const bytes = readFileSync(new URL(`public/${asset.file}`, root));
    if (bytes.length !== asset.bytes || createHash("sha256").update(bytes).digest("hex") !== asset.sha256)
      throw new Error(`wasm_runtime_asset_mismatch:${asset.file}`);
  }
  return definitions;
}
export function writeWasmRuntimeAssets(root = ROOT) {
  const definitions = deriveWasmRuntimeAssets(root);
  for (const { canonical, asset } of definitions) {
    const target = fileURLToPath(new URL(`public/${asset.file}`, root));
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(new URL(canonical, root), target);
  }
  writeFileSync(new URL(GENERATED, root), contents(definitions));
  return definitions;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  console.log(JSON.stringify(process.argv.includes("--write") ? writeWasmRuntimeAssets() : assertWasmRuntimeAssets()));
