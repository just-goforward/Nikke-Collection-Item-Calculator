//! Outward interval roots. No platform sin/cos accuracy assumption.
use super::Result;
use super::spectral::{Category, Complex, Ledger};

fn down(x: f64) -> f64 {
    if x == f64::NEG_INFINITY { return x; }
    if x == 0.0 { return -f64::from_bits(1); }
    f64::from_bits(if x > 0.0 { x.to_bits() - 1 } else { x.to_bits() + 1 })
}
fn up(x: f64) -> f64 { -down(-x) }
#[derive(Clone, Copy)]
struct Interval { lo: f64, hi: f64 }
impl Interval {
    fn point(x: f64) -> Self { Self { lo: x, hi: x } }
    fn add(self, b: Self, ledger: &mut Ledger) -> Result<Self> {
        ledger.charge(Category::Roots, 2)?;
        Ok(Self { lo: down(self.lo + b.lo), hi: up(self.hi + b.hi) })
    }
    fn neg(self) -> Self { Self { lo: -self.hi, hi: -self.lo } }
    fn multiply(self, b: Self, ledger: &mut Ledger) -> Result<Self> {
        ledger.charge(Category::Roots, 4)?;
        let p = [self.lo * b.lo, self.lo * b.hi, self.hi * b.lo, self.hi * b.hi];
        Ok(Self { lo: down(p.into_iter().fold(f64::INFINITY, f64::min)),
            hi: up(p.into_iter().fold(f64::NEG_INFINITY, f64::max)) })
    }
    fn divide_positive(self, n: f64, ledger: &mut Ledger) -> Result<Self> {
        if !(n > 0.0 && n.is_finite()) { return Err("joint_source_contract"); }
        ledger.charge(Category::Roots, 2)?;
        Ok(Self { lo: down(self.lo / n), hi: up(self.hi / n) })
    }
}

// Machin's identity with alternating-series enclosures proves this binary64
// pi bracket in the request, rather than trusting a decimal literal's accuracy.
fn pi(ledger: &mut Ledger) -> Result<Interval> {
    // Fixed-point directed integer arithmetic makes this proof allocation-free.
    // Every bound is an integer multiple of 2^-120; all intermediates fit i128.
    fn atan_reciprocal(d: u128, count: u32, ledger: &mut Ledger) -> Result<(i128, i128)> {
        const SCALE: u128 = 1u128 << 120;
        ledger.charge(Category::Roots, 6)?;
        let square = d * d;
        let mut power_lo = SCALE / d;
        let mut power_hi = SCALE.div_ceil(d);
        let (mut lo, mut hi) = (0i128, 0i128);
        for j in 0..count {
            // ceil division conservatively charged as division/add/subtract.
            ledger.charge(Category::Roots, 14)?;
            let divisor = u128::from(2 * j + 1);
            let a = (power_lo / divisor) as i128;
            let b = power_hi.div_ceil(divisor) as i128;
            if j % 2 == 0 { lo += a; hi += b; } else { lo -= b; hi -= a; }
            power_lo /= square;
            power_hi = power_hi.div_ceil(square);
        }
        ledger.charge(Category::Roots, 6)?;
        let remainder = power_hi.div_ceil(u128::from(2 * count + 1)) as i128;
        if count % 2 == 0 { hi += remainder; } else { lo -= remainder; }
        Ok((lo, hi))
    }
    let (a, b) = atan_reciprocal(5, 40, ledger)?;
    let (c, d) = atan_reciprocal(239, 12, ledger)?;
    ledger.charge(Category::Roots, 8)?;
    let lower = 16 * a - 4 * d;
    let upper = 16 * b - 4 * c;
    let lo = f64::from_bits(0x400921fb54442d18);
    let hi = f64::from_bits(0x400921fb54442d19);
    // Exact adjacent binary64 values, scaled by 2^120.
    let lo_exact = 0x1921fb54442d18i128 << 69;
    let hi_exact = 0x1921fb54442d19i128 << 69;
    if !(lo_exact < lower && upper < hi_exact) { return Err("joint_source_contract"); }
    Ok(Interval { lo, hi })
}

pub(crate) fn fill(roots: &mut [Complex], ledger: &mut Ledger) -> Result<()> {
    let n = roots.len();
    if n == 0 || n > 300 { return Err("joint_source_contract"); }
    let pi = pi(ledger)?;
    for (k, root) in roots.iter_mut().enumerate() {
        ledger.charge(Category::Roots, 10)?;
        // Nearest quarter turn is integer-only; residual lies in [-n/2,n/2].
        let quarter = (4 * k + n / 2) / n;
        let residual = 4 * k as i64 - quarter as i64 * n as i64;
        if residual == 0 {
            *root = match quarter % 4 {
                0 => Complex { re: 1.0, im: 0.0 },
                1 => Complex { re: 0.0, im: -1.0 },
                2 => Complex { re: -1.0, im: 0.0 },
                _ => Complex { re: 0.0, im: 1.0 },
            };
            continue;
        }
        ledger.charge(Category::Roots, 3)?; // two conversions and denominator product
        let x = pi.multiply(Interval::point(residual as f64), ledger)?.divide_positive(2.0 * n as f64, ledger)?;
        let square = x.multiply(x, ledger)?;
        // Horner form, with factorial coefficients generated by exact small
        // integer products represented as outward interval divisions.
        fn polynomial(square: Interval, odd: bool, ledger: &mut Ledger) -> Result<Interval> {
            let mut result = Interval::point(1.0);
            let top = if odd { 11usize } else { 12usize };
            for j in (1..=top).rev() {
                // Construct a, a+1, their product and its numeric conversion.
                ledger.charge(Category::Roots, if odd { 4 } else { 5 })?;
                let a = if odd { 2 * j } else { 2 * j - 1 };
                result = result.multiply(square, ledger)?.divide_positive((a * (a + 1)) as f64, ledger)?.neg()
                    .add(Interval::point(1.0), ledger)?;
            }
            Ok(result)
        }
        let mut sine = polynomial(square, true, ledger)?.multiply(x, ledger)?;
        let mut cosine = polynomial(square, false, ledger)?;
        // |x|<1: the first omitted terms are bounded by 1/25! and
        // 1/26!, both strictly below 2^-83. Use this larger exact dyadic.
        let remainder = f64::from_bits(((1023 - 83) as u64) << 52);
        sine = sine.add(Interval { lo: -remainder, hi: remainder }, ledger)?;
        cosine = cosine.add(Interval { lo: -remainder, hi: remainder }, ledger)?;
        let (re, im) = match quarter % 4 {
            0 => (cosine, sine.neg()),
            1 => (sine.neg(), cosine.neg()),
            2 => (cosine.neg(), sine),
            _ => (sine, cosine),
        };
        ledger.charge(Category::Roots, 16)?;
        let real = re.lo + (re.hi - re.lo) * 0.5;
        let imag = im.lo + (im.hi - im.lo) * 0.5;
        let dr = up((real - re.lo).max(re.hi - real));
        let di = up((imag - im.lo).max(im.hi - imag));
        let radius_squared = up(up(dr * dr) + up(di * di));
        if !radius_squared.is_finite() || radius_squared > f64::from_bits(((1023 - 94) as u64) << 52) {
            return Err("joint_source_integer_limit");
        }
        *root = Complex { re: real, im: imag };
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn certified_axes_and_conjugates() {
        let mut roots = [Complex::ZERO; 300];
        fill(&mut roots, &mut Ledger::default()).unwrap();
        assert_eq!((roots[0].re, roots[75].im, roots[150].re, roots[225].im), (1.0, -1.0, -1.0, 1.0));
        for k in 1..150 {
            assert!((roots[k].re - roots[300-k].re).abs() <= 2f64.powi(-46));
            assert!((roots[k].im + roots[300-k].im).abs() <= 2f64.powi(-46));
        }
    }
}
